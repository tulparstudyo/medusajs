function iconName(componentName: string) {
  return componentName
    .replace(/Icon$/, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .toLowerCase()
}

const sectionIconNames = Object.keys(OutlineIcons)
  .filter((key) => key.endsWith("Icon"))
  .map(iconName)
  .sort()

export const SECTION_ICONS = sectionIconNames as [string, ...string[]]

const sectionIconSet = new Set<string>(SECTION_ICONS)

export type SectionIcon = string

export function isSectionIcon(value: unknown): value is string {
  return typeof value === "string" && sectionIconSet.has(value)
}

export function sectionIconLabel(name: string) {
  const override = OVERRIDES[name]
  if (override) {
    return override
  }

  return name
    .split("-")
    .map((word) => WORDS[word] ?? word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ")
}
